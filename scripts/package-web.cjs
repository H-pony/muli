'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { stageServer, assertClean } = require('../desktop/scripts/stage-server.cjs');
const root = path.resolve(__dirname, '..');
const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
const desktopStage = path.join(root, 'desktop', '.staging');
const manifestPath = path.join(desktopStage, 'server-manifest.json');
const buildId = fs.readFileSync(path.join(root, '.next', 'BUILD_ID'), 'utf8').trim();
if (!fs.existsSync(manifestPath) || JSON.parse(fs.readFileSync(manifestPath, 'utf8')).buildId !== buildId) stageServer();
const generated = path.join(root, 'artifacts', 'releases');
fs.mkdirSync(generated, { recursive: true });
const working = fs.mkdtempSync(path.join(generated, 'web-'));
const name = '幕里-Web';
const bundle = path.join(working, name);
fs.cpSync(path.join(desktopStage, 'server'), bundle, { recursive: true, dereference: true });
assertClean(bundle);
fs.copyFileSync(path.join(desktopStage, 'sources.json'), path.join(bundle, 'sources.json'));
fs.copyFileSync(path.join(root, 'LICENSE'), path.join(bundle, 'LICENSE'));
const start = `'use strict';
const fs = require('node:fs');
const path = require('node:path');
process.env.NODE_ENV = 'production';
process.env.NEXT_TELEMETRY_DISABLED = '1';
process.env.HOSTNAME = process.env.KONGWOTV_HOST || '0.0.0.0';
process.env.PORT = process.env.PORT || '8080';
process.env.PASSWORD ??= '';
const sources = JSON.parse(fs.readFileSync(path.join(__dirname, 'sources.json'), 'utf8'));
process.env.DEFAULT_SOURCES ??= JSON.stringify(sources.vodSources || []);
console.log('幕里 已配置；请打开 http://localhost:' + process.env.PORT);
require('./server.js');
`;
fs.writeFileSync(path.join(bundle, 'start.cjs'), start);
fs.writeFileSync(path.join(bundle, 'start.sh'), '#!/bin/sh\nset -eu\ncd -- "$(dirname -- "$0")"\nexec node start.cjs\n', { mode: 0o755 });
fs.writeFileSync(path.join(bundle, '启动.bat'), '@echo off\r\ncd /d "%~dp0"\r\nnode start.cjs\r\npause\r\n');
const pkgPath = path.join(bundle, 'package.json');
const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
pkg.name = 'muli';
pkg.scripts = { start: 'node start.cjs' };
fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
fs.writeFileSync(path.join(bundle, '安装说明.txt'), `幕里 Web / PWA ${version}\n\n此包包含生产服务端、全部页面、静态资源、预置源和所需 JavaScript 依赖。\n安装 Node.js 22 LTS 或更新版本后，解压并运行 node start.cjs，无需 npm install。\nWindows 也可双击“启动.bat”；macOS/Linux 可执行 ./start.sh。\n打开 http://localhost:8080；默认直接使用，无需访问密码。\n如需启用访问验证，请在启动前显式设置非空 PASSWORD 环境变量。\n旧版 .kongwotv-access.json 不再读取，也不会生成新密码文件。\n也可设置 PORT、KONGWOTV_HOST 等环境变量。\n\n部署到公网时请通过反向代理提供 HTTPS；手机和桌面浏览器可添加到主屏幕，安装名称为幕里。\niPhone/iPad 使用 Safari → 分享 → 添加到主屏幕。\nAndroid 使用 Chrome/Edge 菜单的“安装应用”或“添加到主屏幕”。\nWeb/PWA 仍依赖此服务器在线；Android 和桌面独立客户端不要求此服务器运行。\n\n项目按 AGPL-3.0-or-later 开源，完整源码随本次发布的源码包提供。\n上游来源：https://github.com/LibreSpark/LibreTV\n`);
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
const output = path.join(root, 'dist', `幕里-Web-${version}.zip`);
if (fs.existsSync(output)) throw new Error('Refusing to overwrite an existing Web release; rename it before rebuilding.');
execFileSync('zip', ['-q', '-r', output, name], { cwd: working, stdio: 'inherit' });
console.log(JSON.stringify({ output, stagedDirectory: bundle, audit: assertClean(path.join(desktopStage, 'server')) }, null, 2));
